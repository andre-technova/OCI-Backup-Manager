function Import-HostsFromFile {
    if ([string]::IsNullOrWhiteSpace($HostsFile)) { return @() }
    if (-not (Test-Path $HostsFile)) { throw "HostsFile nao encontrado: $HostsFile" }

    $extension = [System.IO.Path]::GetExtension($HostsFile)
    if ($extension -ieq ".csv") {
        $csvHosts = Import-Csv $HostsFile
        if ($csvHosts -and ($csvHosts[0].PSObject.Properties.Name -contains "Hostname")) {
            return Convert-ToList @($csvHosts | ForEach-Object { $_.Hostname })
        }
    }

    $content = Get-Content $HostsFile -Raw
    return Convert-ToList @($content -split "[\r\n,;]+")
}

function Test-ValueInFilter {
    param([string]$Value, [string[]]$Filter)
    if ($Filter.Count -eq 0) { return $true }
    foreach ($item in $Filter) {
        if ([string]::IsNullOrWhiteSpace($item)) { continue }
        if ($Value -eq $item) { return $true }
    }
    return $false
}


function Normalize-HostToken {
    param([object]$Value)

    if ($null -eq $Value) { return "" }

    $textValue = [string]$Value
    if ([string]::IsNullOrWhiteSpace($textValue)) { return "" }

    return $textValue.Trim().ToUpperInvariant()
}

function Get-InventoryPropertyValue {
    param(
        [object]$Row,
        [string]$PropertyName
    )

    if ($null -eq $Row) { return "" }
    if ([string]::IsNullOrWhiteSpace($PropertyName)) { return "" }

    $property = $Row.PSObject.Properties[$PropertyName]
    if ($null -eq $property -or $null -eq $property.Value) { return "" }

    return ([string]$property.Value).Trim()
}

function Get-InventoryRowHostAliases {
    param([object]$Row)

    $aliasList = @()

    foreach ($propertyName in @("Hostname", "FQDN", "HostnameLabel", "VnicDisplayName", "DisplayName", "Name", "PrivateIP")) {
        $value = Get-InventoryPropertyValue -Row $Row -PropertyName $propertyName
        if (-not [string]::IsNullOrWhiteSpace($value)) {
            $aliasList += $value

            if ($value.Contains('.')) {
                $shortName = ($value -split '\.')[0]
                if (-not [string]::IsNullOrWhiteSpace($shortName)) { $aliasList += $shortName }
            }
        }
    }

    return @($aliasList | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_) } | Select-Object -Unique)
}

function Test-InventoryRowMatchesHost {
    param(
        [object]$Row,
        [string]$HostQuery,
        [switch]$Loose
    )

    $target = Normalize-HostToken $HostQuery
    if ([string]::IsNullOrWhiteSpace($target)) { return $false }

    foreach ($alias in @(Get-InventoryRowHostAliases -Row $Row)) {
        $normalizedAlias = Normalize-HostToken $alias
        if ([string]::IsNullOrWhiteSpace($normalizedAlias)) { continue }

        if ($normalizedAlias -eq $target) { return $true }

        if ($Loose) {
            # PT-BR: Match flexivel controlado para casos como SERVICO01 -> SIA-SERVICO01.
            # EN-US: Controlled loose match for operational aliases like SERVICO01 -> SIA-SERVICO01.
            # ES-ES: Coincidencia flexible controlada para alias operacionales como SERVICO01 -> SIA-SERVICO01.
            if ($normalizedAlias -like "*-$target" -or
                $normalizedAlias -like "*_$target" -or
                $normalizedAlias -like "*.$target" -or
                $normalizedAlias -like "*$target*") {
                return $true
            }
        }
    }

    return $false
}

function Find-InventoryRowsByHost {
    param(
        [object[]]$InventoryRows,
        [string]$HostQuery
    )

    $target = Normalize-HostToken $HostQuery
    if ([string]::IsNullOrWhiteSpace($target)) { return @() }

    $exactRows = @()
    foreach ($row in @($InventoryRows)) {
        if (Test-InventoryRowMatchesHost -Row $row -HostQuery $target) {
            $exactRows += $row
        }
    }

    if ($exactRows.Count -gt 0) { return @($exactRows) }

    $looseRows = @()
    foreach ($row in @($InventoryRows)) {
        if (Test-InventoryRowMatchesHost -Row $row -HostQuery $target -Loose) {
            $looseRows += $row
        }
    }

    return @($looseRows)
}

function Show-HostLookupSuggestions {
    param(
        [object[]]$InventoryRows,
        [string]$HostQuery
    )

    $term = Normalize-HostToken $HostQuery
    if ([string]::IsNullOrWhiteSpace($term)) { return }

    $suggestions = @()
    foreach ($row in @($InventoryRows)) {
        foreach ($alias in @(Get-InventoryRowHostAliases -Row $row)) {
            $normalizedAlias = Normalize-HostToken $alias
            if ($normalizedAlias -like "*$term*") {
                $suggestions += $row
                break
            }
        }
        if ($suggestions.Count -ge 10) { break }
    }

    if ($suggestions.Count -gt 0) {
        Write-Warn "Sugestoes encontradas no inventario para '$HostQuery':"
        foreach ($row in $suggestions) {
            Write-Host ("  - {0} | State={1} | Region={2} | Compartment={3}" -f $row.Hostname, $row.State, $row.Region, $row.CompartmentName) -ForegroundColor Gray
        }
    }
    else {
        Write-Warn "Nenhuma sugestao por aproximacao encontrada para '$HostQuery'. Confirme Hostname/FQDN/HostnameLabel/DisplayName no CSV."
    }
}

function Test-InventoryRowRunning {
