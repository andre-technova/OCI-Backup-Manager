function Read-OptionalCsvList {
    param(
        [string]$Prompt,
        [string]$Default = ""
    )

    $text = Read-MenuText -Prompt $Prompt -Default $Default
    if ([string]::IsNullOrWhiteSpace($text)) { return @() }
    return @(Convert-ToList @($text))
}

function Read-BackupTypeFromMenu {
    param([string]$Default = "FULL")

    if ([string]::IsNullOrWhiteSpace($Default)) { $Default = "FULL" }
    if (@("FULL", "INCREMENTAL") -notcontains $Default.ToUpperInvariant()) { $Default = "FULL" }

    Write-Host ""
    Write-Host "Tipo de backup:" -ForegroundColor Cyan
    Write-Host "  1) FULL        - copia completa do Boot Volume. Recomendado para pre-patch critico/auditoria." -ForegroundColor Gray
    Write-Host "  2) INCREMENTAL - copia incremental. Use quando a cadeia/base de backup estiver aprovada." -ForegroundColor Gray
    Write-Host ""

    while ($true) {
        $answer = (Read-MenuText -Prompt "Escolha o tipo de backup: 1=FULL / 2=INCREMENTAL" -Default $Default).Trim().ToUpperInvariant()
        switch ($answer) {
            "1" { return "FULL" }
            "FULL" { return "FULL" }
            "2" { return "INCREMENTAL" }
            "INCREMENTAL" { return "INCREMENTAL" }
            default { Write-Warn "Opcao invalida. Digite 1/FULL ou 2/INCREMENTAL." }
        }
    }
}

function Read-FilterScopeFromMenu {
    param([bool]$RealBackup)

    if ($RealBackup) {
        Show-MenuOptionHeader `
            -Title "OPCAO 3 - CRIAR BACKUP REAL por filtro" `
            -RiskLevel "ALTO - cria Boot Volume Backup para todos os hosts selecionados pelo filtro" `
            -WhatItDoes "le o inventario, aplica filtros, valida State=RUNNING, valida BootVolumeOCID e cria backup real" `
            -WhatItDoesNotDo "nao e relatorio, nao e simulacao, nao executa patch e nao liga/desliga VM"
        Write-Warn "Recomendacao operacional: rode primeiro a opcao 4 com os mesmos filtros."
        Write-Warn "Filtros amplos podem selecionar muitos hosts e gerar consumo/custo de backup."
        if (-not (Read-MenuYesNo -Prompt "Deseja apenas montar o escopo de backup real por filtro? A criacao ainda sera confirmada depois" -Default $false)) {
            $Script:MenuRequestedExit = $true
            return
        }
    }
    else {
        Show-MenuOptionHeader `
            -Title "OPCAO 4 - DRYRUN por filtro" `
            -RiskLevel "BAIXO - simulacao/validacao, sem criar backup" `
            -WhatItDoes "le o inventario, aplica filtros, mostra escopo e gera evidencias do que seria feito" `
            -WhatItDoesNotDo "nao cria Boot Volume Backup, nao altera recurso OCI e nao executa patch"
    }

    $Script:HostnameLike = Read-MenuText -Prompt "HostnameLike opcional. Ex: APP-* / ESRV* / *GITLAB*" -Default $Script:HostnameLike
    $Script:RegionFilter = @(Read-OptionalCsvList -Prompt "RegionFilter opcional. Ex: sa-saopaulo-1" -Default "")
    $stateText = Read-MenuText -Prompt "StateFilter" -Default "RUNNING"
    $Script:StateFilter = @(Convert-ToList @($stateText))
    $Script:CompartmentNameFilter = @(Read-OptionalCsvList -Prompt "CompartmentNameFilter opcional. Ex: SOA,SERVICES" -Default "")
    $Script:PatchGroupFilter = Read-MenuText -Prompt "PatchGroupFilter opcional. Ex: JANELA-01 / TS" -Default ""
    $Script:ApplicationFilter = Read-MenuText -Prompt "ApplicationFilter opcional. Ex: JENKINS / IIS / GLPI" -Default ""
    $Script:BackupType = Read-BackupTypeFromMenu -Default $Script:BackupType
    $Script:MaxHosts = Read-MenuInt -Prompt "MaxHosts para proteger contra escopo amplo" -Default $Script:MaxHosts -Min 1 -Max 999

    $hasNarrowFilter = (-not [string]::IsNullOrWhiteSpace($Script:HostnameLike)) -or
        ($Script:RegionFilter.Count -gt 0) -or
        ($Script:CompartmentNameFilter.Count -gt 0) -or
        (-not [string]::IsNullOrWhiteSpace($Script:PatchGroupFilter)) -or
        (-not [string]::IsNullOrWhiteSpace($Script:ApplicationFilter))

    if (-not $hasNarrowFilter) {
        Write-Warn "Voce informou apenas StateFilter ou nenhum filtro de reducao real. Isso pode virar escopo amplo."
        Write-Warn "O script ainda respeitara MaxHosts e bloqueios de seguranca, mas revise antes de seguir."
        if ($RealBackup -and -not (Read-MenuYesNo -Prompt "Continuar mesmo assim para calcular o escopo?" -Default $false)) {
            $Script:MenuRequestedExit = $true
            return
        }
    }

    $Script:DryRun = -not $RealBackup
}

