    return ($state -ieq "RUNNING")
}

function Resolve-TargetRows {
    param([object[]]$InventoryRows)

    $hostList = @()

    foreach ($h in @(Convert-ToList -Items $Hosts)) {
        if (-not [string]::IsNullOrWhiteSpace([string]$h)) { $hostList += ([string]$h).Trim() }
    }

    foreach ($h in @(Import-HostsFromFile)) {
        if (-not [string]::IsNullOrWhiteSpace([string]$h)) { $hostList += ([string]$h).Trim() }
    }

    $uniqueHosts = @($hostList | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_) } | Select-Object -Unique)
    $selected = @()

    if ($uniqueHosts.Count -gt 0) {
        foreach ($hostNameQuery in $uniqueHosts) {
            $foundRows = @(Find-InventoryRowsByHost -InventoryRows $InventoryRows -HostQuery $hostNameQuery)
            if ($foundRows.Count -eq 0) {
                Write-Warn "Host nao encontrado no inventario: $hostNameQuery"
                Show-HostLookupSuggestions -InventoryRows $InventoryRows -HostQuery $hostNameQuery
            }
            else {
                foreach ($row in $foundRows) { $selected += $row }
            }
        }
    }
    else {
        if (-not $AllFromCsv -and [string]::IsNullOrWhiteSpace($HostnameLike) -and $RegionFilter.Count -eq 0 -and $CompartmentNameFilter.Count -eq 0 -and [string]::IsNullOrWhiteSpace($PatchGroupFilter) -and [string]::IsNullOrWhiteSpace($ApplicationFilter)) {
            throw "Nenhum host ou filtro informado. Use menu, -Hosts, -HostnameLike, -AllFromCsv ou -DryRun com filtro."
        }

        $selected = @($InventoryRows)
    }

    if (-not [string]::IsNullOrWhiteSpace($HostnameLike)) {
        $selected = @($selected | Where-Object {
            $rowMatchesPattern = $false
            foreach ($alias in @(Get-InventoryRowHostAliases -Row $_)) {
                if ([string]$alias -like $HostnameLike) { $rowMatchesPattern = $true; break }
            }
            $rowMatchesPattern
        })
    }

    if ($RegionFilter.Count -gt 0) {
        $selected = @($selected | Where-Object { Test-ValueInFilter -Value ([string]$_.Region) -Filter $RegionFilter })
    }

    if ($StateFilter.Count -gt 0) {
        $selected = @($selected | Where-Object { Test-ValueInFilter -Value ([string]$_.State) -Filter $StateFilter })
    }

    if ($CompartmentNameFilter.Count -gt 0) {
        $selected = @($selected | Where-Object { Test-ValueInFilter -Value ([string]$_.CompartmentName) -Filter $CompartmentNameFilter })
    }

    if (-not [string]::IsNullOrWhiteSpace($PatchGroupFilter)) {
        $selected = @($selected | Where-Object { [string]$_.PatchGroup -eq $PatchGroupFilter })
    }

    if (-not [string]::IsNullOrWhiteSpace($ApplicationFilter)) {
        $selected = @($selected | Where-Object { [string]$_.Application -eq $ApplicationFilter })
    }

    $dedup = @{}
    $resultRows = @()
    foreach ($row in @($selected)) {
        $key = Get-InventoryPropertyValue -Row $row -PropertyName "InstanceOCID"
        if ([string]::IsNullOrWhiteSpace($key)) { $key = Get-InventoryPropertyValue -Row $row -PropertyName "Hostname" }
        if ([string]::IsNullOrWhiteSpace($key)) { continue }

        if (-not $dedup.ContainsKey($key)) {
            $dedup[$key] = $true
            $resultRows += $row
        }
    }

    Write-Info "Alvos selecionados: $(@($resultRows).Count) host(s)."
    return @($resultRows)
}

function Validate-TargetScope {
    param([object[]]$Rows)

    if (-not $Rows -or @($Rows).Count -eq 0) {
        throw "Nenhum host elegivel encontrado para o escopo informado."
    }

    $nonRunning = @($Rows | Where-Object { -not (Test-InventoryRowRunning -Row $_) })
    if ($nonRunning.Count -gt 0 -and -not $AllowNonRunningBackup) {
        Write-Warn "Instancia(s) fora do estado RUNNING encontradas no escopo:"
        foreach ($row in $nonRunning) {
            Write-Host ("  - {0} | State={1} | Region={2} | Compartment={3}" -f $row.Hostname, $row.State, $row.Region, $row.CompartmentName) -ForegroundColor Yellow
        }
        throw "Backup bloqueado por seguranca operacional: por padrao, o OCI Backup Manager v1.0 exige State=RUNNING. Use -AllowNonRunningBackup somente se o backup de instancia parada tiver sido aprovado."
    }

    $count = @($Rows).Count
    Write-Info "Escopo resolvido: $count host(s)."

    foreach ($row in @($Rows)) {
        Write-Host ("  - {0} | {1} | {2} | {3}" -f $row.Hostname, $row.Region, $row.State, $row.PatchGroup) -ForegroundColor Gray
    }

    if ($count -gt $MaxHosts -and -not $ForceBroadBackup) {
        throw "Escopo possui $count host(s), acima de MaxHosts=$MaxHosts. Use -MaxHosts maior e -ForceBroadBackup somente com aprovacao."
    }

    if (-not $DryRun -and -not $ForceCreateBackup) {
        Show-OperationalRisk
        if ($NoMenu) {
            throw "Criacao de backup em -NoMenu exige -ForceCreateBackup. Para validar sem criar recurso, use -DryRun."
        }
        return (Confirm-RealBackupAfterScope -Count $count -CurrentBackupType $BackupType)
    }

    return $true
}


function New-BackupStatusReportRow {
    param(
        [object]$SourceRow,
        [string]$BootVolumeOCID = "",
        [object]$Backup = $null,
        [string]$QueryStatus = "OK",
        [string]$ErrorMessage = ""
    )

    $backupCompartmentId = ""
    $backupCompartmentName = ""

    if ($null -ne $Backup) {
        $backupCompartmentId = Get-InventoryPropertyValue -Row $Backup -PropertyName "compartment-id"
    }

    if ([string]::IsNullOrWhiteSpace($backupCompartmentId)) {
        $backupCompartmentId = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "CompartmentOCID"
    }

    $sourceCompartmentId = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "CompartmentOCID"
    if ($backupCompartmentId -eq $sourceCompartmentId) {
        $backupCompartmentName = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "CompartmentName"
    }
    elseif ($null -ne $Script:CompartmentNameByOCID -and $Script:CompartmentNameByOCID.ContainsKey($backupCompartmentId)) {
        $backupCompartmentName = [string]$Script:CompartmentNameByOCID[$backupCompartmentId]
    }
    else {
        $backupCompartmentName = "UNKNOWN_FROM_INVENTORY"
    }

    return [pscustomobject]@{
        ReportDateTime             = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
        Hostname                   = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "Hostname"
        FQDN                       = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "FQDN"
        Region                     = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "Region"
        InstanceState              = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "State"
        InstanceCompartmentName    = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "CompartmentName"
        InstanceCompartmentOCID    = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "CompartmentOCID"
        BackupCompartmentName      = $backupCompartmentName
        BackupCompartmentOCID      = $backupCompartmentId
        InstanceOCID               = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "InstanceOCID"
        BootVolumeOCID             = $BootVolumeOCID
        BackupDisplayName          = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "display-name" } else { "" }
        BackupOCID                 = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "id" } else { "" }
        BackupLifecycleState       = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "lifecycle-state" } else { "" }
        BackupType                 = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "type" } else { "" }
        BackupTimeCreated          = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "time-created" } else { "" }
        BackupSizeInGBs            = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "size-in-gbs" } else { "" }
        BackupUniqueSizeInGBs      = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "unique-size-in-gbs" } else { "" }
        SourceType                 = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "source-type" } else { "" }
        ExpirationTime             = if ($null -ne $Backup) { Get-InventoryPropertyValue -Row $Backup -PropertyName "expiration-time" } else { "" }
        QueryStatus                = $QueryStatus
        ErrorMessage               = $ErrorMessage
    }
}

