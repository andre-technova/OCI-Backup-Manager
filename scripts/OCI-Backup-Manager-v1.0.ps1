    Write-StatusFile -Status "BACKUP_STATUS_REPORT_COMPLETED" -Details "Hosts=$hostCount; Rows=$(@($sortedRows).Count); BackupsOK=$okCount; NoBackups=$noBackupCount; Fail=$failCount; CSV=$reportCsv; Screenshot=$screenshotStatus"

