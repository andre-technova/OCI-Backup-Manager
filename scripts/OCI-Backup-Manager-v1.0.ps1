function Get-RecentBackupValidationDecision {
    param(
        [object]$SourceRow,
        [object[]]$Backups,
        [object]$LastAvailableBackup,
        [int]$AvailableCount
    )

    $instanceState = Get-InventoryPropertyValue -Row $SourceRow -PropertyName "State"
    $totalCount = @($Backups).Count

    if ($totalCount -eq 0) {
        return [pscustomobject]@{
            ValidationStatus = "BLOCKED_NO_BACKUP"
            Recommendation   = "Bloquear patch ate existir backup de Boot Volume registrado para este host."
        }
    }

    if ($AvailableCount -eq 0 -or $null -eq $LastAvailableBackup) {
        return [pscustomobject]@{
            ValidationStatus = "BLOCKED_BACKUP_NOT_AVAILABLE"
            Recommendation   = "Bloquear patch: ha backup(s), mas nenhum esta AVAILABLE. Verificar lifecycle-state antes de continuar."
        }
    }

    $lastTimeRaw = Get-InventoryPropertyValue -Row $LastAvailableBackup -PropertyName "time-created"
    $lastUtc = Convert-OciBackupTimeToUtcDateTime -Value $lastTimeRaw
    if ($lastUtc -eq [datetime]::MinValue) {
        return [pscustomobject]@{
            ValidationStatus = "BLOCKED_BACKUP_TIME_INVALID"
            Recommendation   = "Bloquear patch: nao foi possivel interpretar a data do ultimo backup AVAILABLE."
        }
    }

    $ageHours = (New-TimeSpan -Start $lastUtc -End (Get-Date).ToUniversalTime()).TotalHours
    if ($ageHours -gt [double]$RecentBackupMaxAgeHours) {
        return [pscustomobject]@{
            ValidationStatus = "BLOCKED_NO_RECENT_BACKUP"
            Recommendation   = "Bloquear patch ou criar novo backup: ultimo backup AVAILABLE esta fora da janela exigida."
        }
    }

    if ($instanceState -ine "RUNNING") {
        return [pscustomobject]@{
            ValidationStatus = "BLOCKED_INSTANCE_NOT_RUNNING"
            Recommendation   = "Backup recente existe, mas a instancia nao esta RUNNING. Validar escopo/janela antes do patch."
        }
    }

    return [pscustomobject]@{
        ValidationStatus = "OK_TO_PATCH"
        Recommendation   = "Backup AVAILABLE recente encontrado dentro da janela exigida. Host liberado para proxima etapa operacional."
    }
}

function Invoke-RecentBackupValidationReport {
    param([object[]]$Rows)

    $reportCsv = $RecentBackupOutputCsv
    if ([string]::IsNullOrWhiteSpace($reportCsv)) { $reportCsv = $DefaultRecentBackupValidationCsv }
    $reportFolder = Split-Path -Path $reportCsv -Parent
    if ([string]::IsNullOrWhiteSpace($reportFolder)) { $reportFolder = $ExecutionRoot }
    Ensure-Directory $reportFolder

    $reportJson = [System.IO.Path]::ChangeExtension($reportCsv, ".json")
    $reportTxt = [System.IO.Path]::ChangeExtension($reportCsv, ".txt")
    $reportJpg = [System.IO.Path]::ChangeExtension($reportCsv, ".jpg")

    $rowsOut = New-Object System.Collections.ArrayList

    foreach ($sourceRow in @($Rows)) {
        $hostname = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "Hostname"
        $region = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "Region"
        $instanceId = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "InstanceOCID"
        $compartmentId = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "CompartmentOCID"
        $availabilityDomain = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "AvailabilityDomain"
        $bootVolumeCsv = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "BootVolumeOCID"

        Write-Info "Validando backup recente para patch: $hostname"

        try {
            if (-not (Ensure-OciAuth -Quiet)) {
                [void]$rowsOut.Add((New-RecentBackupValidationRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeCsv -QueryStatus "AUTH_ERROR" -ValidationStatus "QUERY_ERROR" -Recommendation "Revalidar autenticacao OCI antes de liberar patch." -ErrorMessage "Sessao OCI invalida durante validacao de backup recente."))
                continue
            }

            $bootVolumeLookup = Get-BootVolumeId `
                -BootVolumeFromCsv $bootVolumeCsv `
                -Region $region `
                -CompartmentId $compartmentId `
                -AvailabilityDomain $availabilityDomain `
                -InstanceId $instanceId

            if (-not $bootVolumeLookup.Success) {
                [void]$rowsOut.Add((New-RecentBackupValidationRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeCsv -QueryStatus "BOOT_VOLUME_ERROR" -ValidationStatus "QUERY_ERROR" -Recommendation "Corrigir BootVolumeOCID/attachment antes de liberar patch." -ErrorMessage $bootVolumeLookup.Error))
                continue
            }

            $bootVolumeId = [string]$bootVolumeLookup.BootVolumeOCID
            $backupList = Get-BootVolumeBackupListByBootVolume -BootVolumeOCID $bootVolumeId -CompartmentOCID $compartmentId -Region $region

            if (-not $backupList.Success) {
                [void]$rowsOut.Add((New-RecentBackupValidationRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeId -QueryStatus "BACKUP_LIST_ERROR" -ValidationStatus "QUERY_ERROR" -Recommendation "Corrigir permissao/consulta OCI antes de liberar patch." -ErrorMessage $backupList.Error))
                continue
            }

            $backups = @(Get-OciListDataItems -OciResult $backupList)
            $latestAnyState = ""
            $latestAny = $null
            $latestAnyCandidates = @()
            foreach ($backup in @($backups)) {
                $timeRaw = Get-InventoryPropertyValue -Row $backup -PropertyName "time-created"
                $latestAnyCandidates += [pscustomobject]@{
                    Backup = $backup
                    ParsedUtc = Convert-OciBackupTimeToUtcDateTime -Value $timeRaw
                }
            }
            $latestAny = @($latestAnyCandidates | Sort-Object -Property ParsedUtc -Descending | Select-Object -First 1)
            if ($null -ne $latestAny) { $latestAnyState = Get-InventoryPropertyValue -Row $latestAny.Backup -PropertyName "lifecycle-state" }

            $availableCandidates = @()
            foreach ($backup in @($backups)) {
                $state = Get-InventoryPropertyValue -Row $backup -PropertyName "lifecycle-state"
                if ($state -ieq "AVAILABLE") {
                    $timeRaw = Get-InventoryPropertyValue -Row $backup -PropertyName "time-created"
                    $availableCandidates += [pscustomobject]@{
                        Backup = $backup
                        ParsedUtc = Convert-OciBackupTimeToUtcDateTime -Value $timeRaw
                    }
                }
            }

            $latestAvailableWrapper = @($availableCandidates | Sort-Object -Property ParsedUtc -Descending | Select-Object -First 1)
            $latestAvailableBackup = $null
            if ($null -ne $latestAvailableWrapper) { $latestAvailableBackup = $latestAvailableWrapper.Backup }

            $totalBackupCount = @($backups).Count
            $availableBackupCount = @($availableCandidates).Count
            $decision = Get-RecentBackupValidationDecision -SourceRow $sourceRow -Backups $backups -LastAvailableBackup $latestAvailableBackup -AvailableCount $availableBackupCount

            [void]$rowsOut.Add((New-RecentBackupValidationRow `
                -SourceRow $sourceRow `
                -BootVolumeOCID $bootVolumeId `
                -LastAvailableBackup $latestAvailableBackup `
                -TotalBackupsFound $totalBackupCount `
                -AvailableBackupsFound $availableBackupCount `
                -LatestAnyBackupState $latestAnyState `
                -QueryStatus "OK" `
                -ValidationStatus $decision.ValidationStatus `
                -Recommendation $decision.Recommendation `
                -ErrorMessage ""))
        }
        catch {
            $errorDetails = $_.Exception.Message
            if ($_.InvocationInfo -and $_.InvocationInfo.ScriptLineNumber) {
                $errorDetails = "$errorDetails | Linha=$($_.InvocationInfo.ScriptLineNumber)"
            }
            [void]$rowsOut.Add((New-RecentBackupValidationRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeCsv -QueryStatus "UNEXPECTED_ERROR" -ValidationStatus "QUERY_ERROR" -Recommendation "Revisar erro inesperado antes de liberar patch." -ErrorMessage $errorDetails))
            Write-Warn "Falha ao validar backup recente para ${hostname}: $errorDetails"
            continue
        }
    }

    $sortedRows = @($rowsOut | Where-Object { $null -ne $_ })
    if (@($sortedRows).Count -eq 0) {
        $sortedRows = @([pscustomobject]@{
            ReportDateTime = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
            QueryStatus = "NO_ROWS"
            ValidationStatus = "QUERY_ERROR"
            Recommendation = "Nenhuma linha gerada. Revalidar escopo."
            ErrorMessage = "Nenhuma linha gerada para a validacao de backup recente."
        })
    }

    $sortedRows | Export-Csv -Path $reportCsv -NoTypeInformation -Encoding UTF8 -Force
    $sortedRows | ConvertTo-Json -Depth 10 | Out-File -FilePath $reportJson -Encoding UTF8 -Force

    $okCount = @($sortedRows | Where-Object { [string]$_.ValidationStatus -eq "OK_TO_PATCH" }).Count
    $blockedCount = @($sortedRows | Where-Object { ([string]$_.ValidationStatus).StartsWith("BLOCKED_") }).Count
    $queryErrorCount = @($sortedRows | Where-Object { [string]$_.ValidationStatus -eq "QUERY_ERROR" }).Count
    $hostCount = @($Rows).Count

    $txt = @"
TOOL: $ToolName
VERSION: $ToolVersion
BUILD: $ToolBuild
REPORT_TYPE: RECENT_BACKUP_VALIDATION
HOSTS_CONSULTADOS: $hostCount
LINHAS_GERADAS: $(@($sortedRows).Count)
OK_TO_PATCH: $okCount
BLOCKED: $blockedCount
QUERY_ERROR: $queryErrorCount
REQUIRED_MAX_AGE_HOURS: $RecentBackupMaxAgeHours
INPUT_CSV: $InputCsv
REPORT_CSV: $reportCsv
REPORT_JSON: $reportJson
REPORT_JPG: $reportJpg
DATE_TIME: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
OBSERVACAO: Validacao somente leitura. Nenhum backup foi criado, alterado ou excluido.
"@
    $txt | Out-File -FilePath $reportTxt -Encoding UTF8 -Force

    [void](Prepare-VisualEvidenceWindow)
    Clear-Host
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "$ToolName v$ToolVersion - Validacao de Backup Recente" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "Data/Hora local: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')" -ForegroundColor Gray
    Write-Host "Relatorio somente leitura. Nenhum backup foi criado, alterado ou excluido." -ForegroundColor Gray
    Write-Host "Janela exigida   : $RecentBackupMaxAgeHours hora(s)" -ForegroundColor Gray
    Write-Host "Hosts consultados: $hostCount" -ForegroundColor Gray
    Write-Host "OK_TO_PATCH      : $okCount" -ForegroundColor Green
    Write-Host "Bloqueados       : $blockedCount" -ForegroundColor Yellow
    Write-Host "Erros consulta   : $queryErrorCount" -ForegroundColor Red
    Write-Host "CSV              : $reportCsv" -ForegroundColor Gray
    Write-Host "JSON             : $reportJson" -ForegroundColor Gray
    Write-Host "TXT              : $reportTxt" -ForegroundColor Gray
    Write-Host "Evidencia visual : $reportJpg" -ForegroundColor Gray
    Write-Host ""
    Write-Host "A captura full screen deve registrar o relogio/data do Windows quando a barra de tarefas estiver visivel." -ForegroundColor Gray

    $screenshotStatus = Save-BackupVisualEvidence -OutputPath $reportJpg
    if ($screenshotStatus -ne "OK") {
        if (Test-Path $reportJpg) { Remove-Item $reportJpg -Force -ErrorAction SilentlyContinue }
        Write-Warn "Evidencia visual da validacao: $screenshotStatus"
    }
    else {
        Write-Ok "Evidencia visual da validacao salva."
    }

    Write-StatusFile -Status "RECENT_BACKUP_VALIDATION_COMPLETED" -Details "Hosts=$hostCount; OK=$okCount; Blocked=$blockedCount; QueryError=$queryErrorCount; MaxAgeHours=$RecentBackupMaxAgeHours; CSV=$reportCsv; Screenshot=$screenshotStatus"

    return [pscustomobject]@{
        HostCount        = $hostCount
        RowCount         = @($sortedRows).Count
        OkCount          = $okCount
        BlockedCount     = $blockedCount
        QueryErrorCount  = $queryErrorCount
        CsvPath          = $reportCsv
        JsonPath         = $reportJson
        TxtPath          = $reportTxt
        JpgPath          = if ($screenshotStatus -eq "OK") { $reportJpg } else { "" }
        ScreenshotStatus = $screenshotStatus
    }
}

function Import-BackupDeleteTargets {
    param(
        [string[]]$OCIDs,
        [string]$InputCsv
    )

    $targets = New-Object System.Collections.ArrayList

    foreach ($ocid in @(Convert-ToList -Items $OCIDs)) {
        if ([string]::IsNullOrWhiteSpace($ocid)) { continue }
        [void]$targets.Add([pscustomobject]@{
            BackupOCID = ([string]$ocid).Trim()
            Region = ""
            Hostname = "DIRECT_OCID"
            BackupDisplayName = ""
            BackupLifecycleState = ""
            BackupType = ""
            BackupTimeCreated = ""
            BackupCompartmentName = ""
            Source = "DIRECT"
        })
    }

    if (-not [string]::IsNullOrWhiteSpace($InputCsv)) {
        if (-not (Test-Path $InputCsv)) { throw "CSV de exclusao nao encontrado: $InputCsv" }
        $csvRows = @(Import-Csv $InputCsv)
        foreach ($row in $csvRows) {
            $backupOcid = Get-InventoryPropertyValue -Row $row -PropertyName "BackupOCID"
            if ([string]::IsNullOrWhiteSpace($backupOcid)) { continue }
            [void]$targets.Add([pscustomobject]@{
                BackupOCID = $backupOcid
                Region = Get-InventoryPropertyValue -Row $row -PropertyName "Region"
                Hostname = Get-InventoryPropertyValue -Row $row -PropertyName "Hostname"
                BackupDisplayName = Get-InventoryPropertyValue -Row $row -PropertyName "BackupDisplayName"
                BackupLifecycleState = Get-InventoryPropertyValue -Row $row -PropertyName "BackupLifecycleState"
                BackupType = Get-InventoryPropertyValue -Row $row -PropertyName "BackupType"
                BackupTimeCreated = Get-InventoryPropertyValue -Row $row -PropertyName "BackupTimeCreated"
                BackupCompartmentName = Get-InventoryPropertyValue -Row $row -PropertyName "BackupCompartmentName"
                Source = "CSV"
            })
        }
    }

    $dedup = @{}
    $clean = @()
    foreach ($target in @($targets)) {
        $id = ([string]$target.BackupOCID).Trim()
        if ([string]::IsNullOrWhiteSpace($id)) { continue }
        if ($id -notmatch '^ocid1\.bootvolumebackup\.') {
            Write-Warn "BackupOCID ignorado por formato inesperado: $id"
            continue
        }
        if (-not $dedup.ContainsKey($id)) {
            $dedup[$id] = $true
            $clean += $target
        }
    }

    return @($clean)
}

function Validate-BackupDeleteScope {
    param([object[]]$Targets)

    if (-not $Targets -or @($Targets).Count -eq 0) {
        throw "Nenhum BackupOCID elegivel para exclusao. Informe OCIDs ou CSV com coluna BackupOCID."
    }

    $count = @($Targets).Count
    Write-Info "Escopo de exclusao de backups OCI: $count backup(s)."
    foreach ($item in @($Targets | Select-Object -First 20)) {
        Write-Host ("  - {0} | {1} | {2} | {3}" -f $item.BackupOCID, $item.Hostname, $item.BackupLifecycleState, $item.BackupTimeCreated) -ForegroundColor Gray
    }
    if ($count -gt 20) { Write-Warn "Lista truncada no console. Total selecionado: $count" }

    if ($count -gt $DeleteMaxBackups -and -not $ForceDeleteBackup) {
        throw "Exclusao possui $count backup(s), acima de DeleteMaxBackups=$DeleteMaxBackups. Aumente -DeleteMaxBackups e use -ForceDeleteBackup somente com aprovacao."
    }

    if ($DryRun) {
        Write-Warn "DryRun de exclusao habilitado. Nenhum backup OCI sera excluido."
        return $true
    }

    if (-not $ForceDeleteBackup) {
        if ($NoMenu) {
            throw "Exclusao real em -NoMenu exige -ForceDeleteBackup. Para validar sem excluir, use -DryRun."
        }
        return (Confirm-BackupDeleteAfterScope -Count $count -Targets $Targets)
    }

    return $true
}

function Remove-OciBootVolumeBackup {
    param(
        [string]$BackupOCID,
        [string]$Region = ""
    )

    if ([string]::IsNullOrWhiteSpace($BackupOCID)) {
        return [pscustomobject]@{ Success = $false; ExitCode = -1; Raw = ""; Error = "BackupOCID vazio." }
    }

    if (-not (Ensure-OciAuth -Quiet)) {
        return [pscustomobject]@{ Success = $false; ExitCode = -1; Raw = ""; Error = "Sessao OCI invalida antes da exclusao." }
    }

    $args = @(
        "bv", "boot-volume-backup", "delete",
        "--boot-volume-backup-id", $BackupOCID,
        "--force"
    )

    $finalArgs = Add-OciCommonArgs -Arguments $args -Region $Region
    $raw = & oci @finalArgs 2>&1
    $exit = $LASTEXITCODE
    $text = ($raw | Out-String).Trim()

    if ($exit -ne 0) {
        return [pscustomobject]@{ Success = $false; ExitCode = $exit; Raw = $text; Error = "OCI CLI retornou codigo $exit ao excluir backup." }
    }

    return [pscustomobject]@{ Success = $true; ExitCode = $exit; Raw = $text; Error = "" }
}

function Invoke-BackupDeleteReport {
    param([object[]]$Targets)

    $reportCsv = $BackupDeleteOutputCsv
    if ([string]::IsNullOrWhiteSpace($reportCsv)) { $reportCsv = $DefaultBackupDeleteReportCsv }
    $reportFolder = Split-Path -Path $reportCsv -Parent
    if ([string]::IsNullOrWhiteSpace($reportFolder)) { $reportFolder = $ExecutionRoot }
    Ensure-Directory $reportFolder

    $reportJson = [System.IO.Path]::ChangeExtension($reportCsv, ".json")
    $reportTxt = [System.IO.Path]::ChangeExtension($reportCsv, ".txt")
    $reportJpg = [System.IO.Path]::ChangeExtension($reportCsv, ".jpg")

    $rowsOut = New-Object System.Collections.ArrayList

    foreach ($target in @($Targets)) {
        $backupOcid = [string]$target.BackupOCID
        $region = [string]$target.Region
        $resultToken = if ($DryRun) { "DELETE_DRYRUN" } else { "PENDING" }
        $errorMessage = ""
        $rawOutput = ""

        Write-Info "Processando exclusao de backup OCI: $backupOcid"

        if ($DryRun) {
            Write-Warn "DryRun: backup OCI NAO sera excluido."
        }
        else {
            $deleteResult = Remove-OciBootVolumeBackup -BackupOCID $backupOcid -Region $region
            $rawOutput = $deleteResult.Raw
            if ($deleteResult.Success) {
                $resultToken = "DELETE_REQUESTED"
                Write-Ok "Exclusao solicitada para backup: $backupOcid"
            }
            else {
                $resultToken = "DELETE_ERROR"
                $errorMessage = $deleteResult.Error
                if (-not [string]::IsNullOrWhiteSpace($deleteResult.Raw)) { $errorMessage = $errorMessage + " | " + $deleteResult.Raw }
                Write-Bad "Falha ao excluir backup OCI."
            }
        }

        [void]$rowsOut.Add([pscustomobject]@{
            ReportDateTime = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
            BackupOCID = $backupOcid
            Region = $region
            Hostname = [string]$target.Hostname
