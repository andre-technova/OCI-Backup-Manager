function Invoke-BackupStatusReport {
    param([object[]]$Rows)

    $reportCsv = $BackupStatusOutputCsv
    if ([string]::IsNullOrWhiteSpace($reportCsv)) { $reportCsv = $DefaultBackupStatusReportCsv }
    $reportFolder = Split-Path -Path $reportCsv -Parent
    if ([string]::IsNullOrWhiteSpace($reportFolder)) { $reportFolder = $ExecutionRoot }
    Ensure-Directory $reportFolder

    $reportJson = [System.IO.Path]::ChangeExtension($reportCsv, ".json")
    $reportTxt = [System.IO.Path]::ChangeExtension($reportCsv, ".txt")
    $reportJpg = [System.IO.Path]::ChangeExtension($reportCsv, ".jpg")

    $rowsOut = New-Object System.Collections.ArrayList

    foreach ($sourceRow in @($Rows)) {
        $hostname = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "Hostname"
        $region = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "Region"
        $instanceId = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "InstanceOCID"
        $compartmentId = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "CompartmentOCID"
        $availabilityDomain = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "AvailabilityDomain"
        $bootVolumeCsv = Get-InventoryPropertyValue -Row $sourceRow -PropertyName "BootVolumeOCID"

        Write-Info "Consultando historico/status de backups: $hostname"

        try {
            if (-not (Ensure-OciAuth -Quiet)) {
                [void]$rowsOut.Add((New-BackupStatusReportRow -SourceRow $sourceRow -QueryStatus "AUTH_ERROR" -ErrorMessage "Sessao OCI invalida durante consulta de status."))
                continue
            }

            $bootVolumeLookup = Get-BootVolumeId `
                -BootVolumeFromCsv $bootVolumeCsv `
                -Region $region `
                -CompartmentId $compartmentId `
                -AvailabilityDomain $availabilityDomain `
                -InstanceId $instanceId

            if (-not $bootVolumeLookup.Success) {
                [void]$rowsOut.Add((New-BackupStatusReportRow -SourceRow $sourceRow -QueryStatus "BOOT_VOLUME_ERROR" -ErrorMessage $bootVolumeLookup.Error))
                continue
            }

            $bootVolumeId = [string]$bootVolumeLookup.BootVolumeOCID
            $backupList = Get-BootVolumeBackupListByBootVolume -BootVolumeOCID $bootVolumeId -CompartmentOCID $compartmentId -Region $region

            if (-not $backupList.Success) {
                [void]$rowsOut.Add((New-BackupStatusReportRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeId -QueryStatus "BACKUP_LIST_ERROR" -ErrorMessage $backupList.Error))
                continue
            }

            $backups = @(Get-OciListDataItems -OciResult $backupList)
            if ($backups.Count -eq 0) {
                [void]$rowsOut.Add((New-BackupStatusReportRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeId -QueryStatus "NO_BACKUPS_FOUND" -ErrorMessage "Nenhum backup encontrado para o Boot Volume no compartimento informado."))
                continue
            }

            foreach ($backup in @($backups)) {
                [void]$rowsOut.Add((New-BackupStatusReportRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeId -Backup $backup -QueryStatus "OK" -ErrorMessage ""))
            }
        }
        catch {
            $errorDetails = $_.Exception.Message
            if ($_.InvocationInfo -and $_.InvocationInfo.ScriptLineNumber) {
                $errorDetails = "$errorDetails | Linha=$($_.InvocationInfo.ScriptLineNumber)"
            }
            [void]$rowsOut.Add((New-BackupStatusReportRow -SourceRow $sourceRow -BootVolumeOCID $bootVolumeCsv -QueryStatus "UNEXPECTED_ERROR" -ErrorMessage $errorDetails))
            Write-Warn "Falha ao consultar ${hostname}: $errorDetails"
            continue
        }
    }

    # PT-BR: no modo status, preservamos a ordem de coleta para evitar falhas de comparacao entre tipos mistos retornados pelo OCI CLI.
    # EN-US: In status mode, preserve collection order to avoid mixed-type comparison issues from OCI CLI JSON.
    # ES-ES: En modo estado, preservamos el orden de recoleccion para evitar fallos de comparacion entre tipos mixtos.
    $sortedRows = @($rowsOut | Where-Object { $null -ne $_ })

    if (@($sortedRows).Count -eq 0) {
        $placeholder = [pscustomobject]@{
            ReportDateTime = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
            QueryStatus    = "NO_ROWS"
            ErrorMessage   = "Nenhuma linha gerada para o relatorio."
        }
        $sortedRows = @($placeholder)
    }

    $sortedRows | Export-Csv -Path $reportCsv -NoTypeInformation -Encoding UTF8 -Force
    $sortedRows | ConvertTo-Json -Depth 10 | Out-File -FilePath $reportJson -Encoding UTF8 -Force

    $okCount = @($sortedRows | Where-Object { [string]$_.QueryStatus -eq "OK" }).Count
    $noBackupCount = @($sortedRows | Where-Object { [string]$_.QueryStatus -eq "NO_BACKUPS_FOUND" }).Count
