function Read-MenuText {
    param([string]$Prompt, [string]$Default = "")
    if ([string]::IsNullOrWhiteSpace($Default)) {
        return (Read-Host $Prompt)
    }

    $answer = Read-Host "$Prompt [$Default]"
    if ([string]::IsNullOrWhiteSpace($answer)) { return $Default }
    return $answer
}

function Read-MenuYesNo {
    param([string]$Prompt, [bool]$Default = $false)
    $defaultText = if ($Default) { "S" } else { "N" }
    while ($true) {
        $answer = (Read-Host "$Prompt (S/N) [$defaultText]").Trim()
        if ([string]::IsNullOrWhiteSpace($answer)) { return $Default }
        switch -Regex ($answer) {
            '^(s|sim|y|yes)$' { return $true }
            '^(n|nao|não|no)$' { return $false }
            default { Write-Warn "Resposta invalida. Digite S ou N." }
        }
    }
}

function Read-MenuInt {
    param([string]$Prompt, [int]$Default, [int]$Min = 1, [int]$Max = 9999)
    while ($true) {
        $answer = Read-Host "$Prompt [$Default]"
        if ([string]::IsNullOrWhiteSpace($answer)) { return $Default }
        $parsed = 0
        if ([int]::TryParse($answer, [ref]$parsed) -and $parsed -ge $Min -and $parsed -le $Max) {
            return $parsed
        }
        Write-Warn "Valor invalido. Informe um numero entre $Min e $Max."
    }
}

function Convert-ToList {
    param([object[]]$Items)
    $list = New-Object System.Collections.Generic.List[string]
    foreach ($item in @($Items)) {
        if ($null -eq $item) { continue }
        foreach ($part in ([string]$item).Split(',')) {
            $value = $part.Trim()
            if (-not [string]::IsNullOrWhiteSpace($value)) { [void]$list.Add($value) }
        }
    }
    return @($list | Select-Object -Unique)
}


