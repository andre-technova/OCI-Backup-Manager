    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "$ToolName v$ToolVersion - Resumo Final" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "Total processado : $(@($Script:RunSummaryRows).Count)" -ForegroundColor Gray
    Write-Host "Sucesso          : $successCount" -ForegroundColor Green
    Write-Host "DryRun           : $dryRunCount" -ForegroundColor Yellow
    Write-Host "Falha            : $failCount" -ForegroundColor Red
    Write-Host "Evidencias       : $ExecutionRoot" -ForegroundColor Gray
    Write-Host "Log CSV          : $ConsolidatedCsv" -ForegroundColor Gray
    Write-Host "Log JSON         : $ConsolidatedJson" -ForegroundColor Gray
    Write-Host ""

    $status = if ($failCount -gt 0) { "COMPLETED_WITH_FAILURES" } elseif ($dryRunCount -gt 0 -and $successCount -eq 0) { "DRYRUN_COMPLETED" } else { "SUCCESS" }
    Write-StatusFile -Status $status -Details "Success=$successCount; DryRun=$dryRunCount; Fail=$failCount"

    if ($failCount -gt 0) { exit 2 }
    exit 0
}
catch {
    $Script:RunHadFailure = $true
    $fatalMessage = $_.Exception.Message
    if ($_.InvocationInfo -and $_.InvocationInfo.ScriptLineNumber) {
        $fatalMessage = "$fatalMessage | Linha=$($_.InvocationInfo.ScriptLineNumber)"
    }
    Write-Bad "Erro fatal: $fatalMessage"
    try { Write-StatusFile -Status "FATAL_ERROR" -Details $fatalMessage } catch { }
    exit 1
}
finally {
    Stop-ExecutionLog
    if ($PauseOnExit) {
        Write-Host ""
        Read-Host "Pressione ENTER para sair"
    }
}
