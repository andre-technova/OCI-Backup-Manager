    $sortedRows | Export-Csv -Path $reportCsv -NoTypeInformation -Encoding UTF8 -Force
    $sortedRows | ConvertTo-Json -Depth 10 | Out-File -FilePath $reportJson -Encoding UTF8 -Force

    $dryRunCount = @($sortedRows | Where-Object { [string]$_.DeleteStatus -eq "DELETE_DRYRUN" }).Count
    $requestedCount = @($sortedRows | Where-Object { [string]$_.DeleteStatus -eq "DELETE_REQUESTED" }).Count
    $failCount = @($sortedRows | Where-Object { [string]$_.DeleteStatus -eq "DELETE_ERROR" }).Count

    $txt = @"
