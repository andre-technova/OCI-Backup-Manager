    Write-Host "DryRun             : $([bool]$DryRun)" -ForegroundColor Gray
    Write-Host "Selecionados       : $(@($Targets).Count)" -ForegroundColor Gray
    Write-Host "Delete DryRun      : $dryRunCount" -ForegroundColor Yellow
    Write-Host "Delete solicitado  : $requestedCount" -ForegroundColor Red
    Write-Host "Falhas             : $failCount" -ForegroundColor Red
    Write-Host "CSV                : $reportCsv" -ForegroundColor Gray
    Write-Host "JSON               : $reportJson" -ForegroundColor Gray
    Write-Host "TXT                : $reportTxt" -ForegroundColor Gray
    Write-Host "Evidencia visual   : $reportJpg" -ForegroundColor Gray
    Write-Host ""
    Write-Host "A captura full screen deve registrar o relogio/data do Windows quando a barra de tarefas estiver visivel." -ForegroundColor Gray

    $screenshotStatus = Save-BackupVisualEvidence -OutputPath $reportJpg
    if ($screenshotStatus -ne "OK") {
        if (Test-Path $reportJpg) { Remove-Item $reportJpg -Force -ErrorAction SilentlyContinue }
        Write-Warn "Evidencia visual da exclusao: $screenshotStatus"
    }
    else {
        Write-Ok "Evidencia visual da exclusao salva."
    }

    Write-StatusFile -Status "BACKUP_DELETE_COMPLETED" -Details "Selected=$(@($Targets).Count); DryRun=$dryRunCount; Requested=$requestedCount; Fail=$failCount; CSV=$reportCsv; Screenshot=$screenshotStatus"

    return [pscustomobject]@{
        SelectedCount = @($Targets).Count
        DryRunCount = $dryRunCount
        RequestedCount = $requestedCount
        FailCount = $failCount
        CsvPath = $reportCsv
        JsonPath = $reportJson
        TxtPath = $reportTxt
        JpgPath = if ($screenshotStatus -eq "OK") { $reportJpg } else { "" }
        ScreenshotStatus = $screenshotStatus
    }
}

function Get-BootVolumeId {
    param(
        [string]$BootVolumeFromCsv,
        [string]$Region,
        [string]$CompartmentId,
        [string]$AvailabilityDomain,
        [string]$InstanceId
    )

    if (-not [string]::IsNullOrWhiteSpace($BootVolumeFromCsv) -and $BootVolumeFromCsv -notmatch "NAO_|NOT_|N/A|ERRO") {
        return [pscustomobject]@{ Success = $true; BootVolumeOCID = $BootVolumeFromCsv; Error = ""; Raw = "CSV" }
    }

    if ([string]::IsNullOrWhiteSpace($Region) -or [string]::IsNullOrWhiteSpace($CompartmentId) -or [string]::IsNullOrWhiteSpace($InstanceId)) {
        return [pscustomobject]@{ Success = $false; BootVolumeOCID = ""; Error = "Region/CompartmentOCID/InstanceOCID ausente para descobrir Boot Volume."; Raw = "" }
    }

    Write-Warn "BootVolumeOCID ausente no CSV. Buscando Boot Volume Attachment..."

    $args = @(
        "compute", "boot-volume-attachment", "list",
        "--compartment-id", $CompartmentId,
        "--instance-id", $InstanceId
    )

    if (-not [string]::IsNullOrWhiteSpace($AvailabilityDomain)) {
        $args += @("--availability-domain", $AvailabilityDomain)
    }

    $result = Invoke-OciCliJson -Context "boot-volume-attachment list" -Arguments $args -Region $Region
    if (-not $result.Success) {
        return [pscustomobject]@{ Success = $false; BootVolumeOCID = ""; Error = $result.Error; Raw = $result.Raw }
    }

    $attachment = @($result.Data.data | Select-Object -First 1)
    if (-not $attachment -or [string]::IsNullOrWhiteSpace($attachment."boot-volume-id")) {
        return [pscustomobject]@{ Success = $false; BootVolumeOCID = ""; Error = "Nenhum Boot Volume Attachment encontrado."; Raw = $result.Raw }
    }

    return [pscustomobject]@{ Success = $true; BootVolumeOCID = $attachment."boot-volume-id"; Error = ""; Raw = $result.Raw }
}

