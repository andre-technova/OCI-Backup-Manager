function Convert-OciBackupTimeToUtcDateTime {
    param([string]$Value)

    if ([string]::IsNullOrWhiteSpace($Value)) { return [datetime]::MinValue }

    try {
        $dto = [datetimeoffset]::MinValue
        if ([datetimeoffset]::TryParse($Value, [System.Globalization.CultureInfo]::InvariantCulture, [System.Globalization.DateTimeStyles]::AssumeUniversal, [ref]$dto)) {
            return $dto.UtcDateTime
        }
    }
    catch { }

    try {
        return ([datetime]::Parse($Value, [System.Globalization.CultureInfo]::InvariantCulture, [System.Globalization.DateTimeStyles]::AssumeUniversal)).ToUniversalTime()
    }
    catch {
        return [datetime]::MinValue
    }
}

function New-RecentBackupValidationRow {
    param(
