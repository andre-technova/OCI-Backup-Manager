        PT-BR: Evita que filtros de uma execucao/menu anterior contaminem a proxima opcao escolhida.
        EN-US: Prevents filters from a previous menu run from leaking into the next selected mode.
        ES-ES: Evita que filtros de una ejecucion/menu anterior contaminen el siguiente modo seleccionado.
    #>
    $Script:Hosts = @()
    $Script:HostnameLike = ""
    $Script:RegionFilter = @()
    $Script:StateFilter = @()
    $Script:CompartmentNameFilter = @()
    $Script:PatchGroupFilter = ""
    $Script:ApplicationFilter = ""
    $Script:AllFromCsv = $false
    $Script:BackupStatusReport = $false
    $Script:RecentBackupValidation = $false
    $Script:DeleteBackupMode = $false
    $Script:BackupDeleteOCIDs = @()
    $Script:BackupDeleteInputCsv = ""
    $Script:ForceDeleteBackup = $false
}

