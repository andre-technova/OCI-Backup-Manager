function Wait-BootVolumeBackupFinalState {
    param([string]$BackupOCID, [string]$Region)

    $deadline = (Get-Date).AddMinutes($BackupMaxWaitMinutes)
    $lastState = "UNKNOWN"
    $lastRaw = ""
    $lastError = ""

    do {
        Start-Sleep -Seconds $BackupPollSeconds
        $status = Get-BootVolumeBackupStatus -BackupOCID $BackupOCID -Region $Region
        $lastRaw = $status.Raw

        if (-not $status.Success) {
            $lastError = $status.Error
            return [pscustomobject]@{ Success = $false; FinalStatus = "ERRO_AO_CONSULTAR_STATUS"; Error = $lastError; Raw = $lastRaw }
        }

        $lastState = [string]$status.Data.data."lifecycle-state"
        if ([string]::IsNullOrWhiteSpace($lastState)) { $lastState = "UNKNOWN" }
        Write-Host "Status do backup: $lastState" -ForegroundColor Gray

        if ($lastState -in @("AVAILABLE", "FAULTY", "TERMINATED")) {
            return [pscustomobject]@{ Success = ($lastState -eq "AVAILABLE"); FinalStatus = $lastState; Error = ""; Raw = $lastRaw }
        }
    } while ((Get-Date) -lt $deadline)

    return [pscustomobject]@{ Success = $false; FinalStatus = "TIMEOUT_AGUARDANDO_BACKUP"; Error = "Backup nao chegou a estado final em $BackupMaxWaitMinutes minuto(s). Ultimo estado: $lastState"; Raw = $lastRaw }
}

function Move-CurrentPowerShellToPrimaryMonitor {
    <#
        PT-BR: move e maximiza o PowerShell no monitor principal antes da captura.
        EN-US: moves and maximizes PowerShell on the primary monitor before capture.
        ES-ES: mueve y maximiza PowerShell en el monitor principal antes de la captura.

        Observacao importante:
        A janela e maximizada na area de trabalho do monitor principal para manter
        a barra do Windows visivel. A captura usa o monitor inteiro, portanto o
        relogio/data do Windows ficam registrados quando a barra de tarefas nao
        estiver oculta automaticamente.
    #>
    if (-not $Script:ScreenshotAvailable) { return }

    $hWnd = [Win32Native]::GetConsoleWindow()
    if ($hWnd -eq [IntPtr]::Zero) { throw "Nao foi possivel identificar a janela atual do PowerShell." }

    $primaryScreen = [System.Windows.Forms.Screen]::PrimaryScreen
    $workArea = $primaryScreen.WorkingArea

    [void][Win32Native]::ShowWindow($hWnd, 9) # SW_RESTORE
    Start-Sleep -Milliseconds 500

    [void][Win32Native]::MoveWindow(
        $hWnd,
        $workArea.X,
        $workArea.Y,
        $workArea.Width,
        $workArea.Height,
        $true
    )

    Start-Sleep -Milliseconds 300
    [void][Win32Native]::ShowWindow($hWnd, 3) # SW_MAXIMIZE
    [void][Win32Native]::SetForegroundWindow($hWnd)
    Start-Sleep -Seconds 2
}

function Prepare-VisualEvidenceWindow {
    <#
        PT-BR: prepara a janela antes da execucao do host para que a evidencia
        visual seja capturada em tela maximizada no monitor principal.
        EN-US: prepares the window before host processing so visual evidence is
        captured maximized on the primary monitor.
        ES-ES: prepara la ventana antes de procesar el host para capturar la
        evidencia visual maximizada en el monitor principal.
    #>
    if ($NoScreenshot) {
        $Script:ConsoleReadyForScreenshot = $false
        return "SCREENSHOT_DISABLED_BY_PARAMETER"
    }

    if (-not $Script:ScreenshotAvailable) {
        $Script:ConsoleReadyForScreenshot = $false
        return "SCREENSHOT_UNAVAILABLE"
    }

    try {
        Move-CurrentPowerShellToPrimaryMonitor
        $Script:ConsoleReadyForScreenshot = $true
        return "OK"
    }
    catch {
        $Script:ConsoleReadyForScreenshot = $false
        Write-Warn "Nao foi possivel preparar a janela para evidencia visual: $($_.Exception.Message)"
        return "FALHA_PREPARAR_JANELA: $($_.Exception.Message)"
    }
}

function Save-PrimaryScreenScreenshot {
    param([Parameter(Mandatory=$true)][string]$OutputPath)

    if (-not $Script:ScreenshotAvailable) { return $false }

    $primaryScreen = [System.Windows.Forms.Screen]::PrimaryScreen
    $bounds = $primaryScreen.Bounds
    $bitmap = New-Object System.Drawing.Bitmap $bounds.Width, $bounds.Height
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)

    try {
        $graphics.CopyFromScreen($bounds.X, $bounds.Y, 0, 0, $bounds.Size)
        $bitmap.Save($OutputPath, [System.Drawing.Imaging.ImageFormat]::Jpeg)
        return $true
    }
    finally {
        $graphics.Dispose()
        $bitmap.Dispose()
    }
}

function Save-BackupVisualEvidence {
    param([Parameter(Mandatory=$true)][string]$OutputPath)

    if ($NoScreenshot -or -not $Script:ScreenshotAvailable) { return "SCREENSHOT_DISABLED_OR_UNAVAILABLE" }

    try {
        Move-CurrentPowerShellToPrimaryMonitor
        Start-Sleep -Seconds 2
        $tempPath = [System.IO.Path]::ChangeExtension($OutputPath, ".tmp.jpg")
        [void](Save-PrimaryScreenScreenshot -OutputPath $tempPath)
        Start-Sleep -Milliseconds 700
        [void](Save-PrimaryScreenScreenshot -OutputPath $OutputPath)
        if (Test-Path $tempPath) { Remove-Item $tempPath -Force -ErrorAction SilentlyContinue }
        return "OK"
    }
    catch {
        return "FALHA_SCREENSHOT: $($_.Exception.Message)"
    }
}

