function Invoke-HostBackup {
    param([object]$Row)

    $hostname = [string]$Row.Hostname
    if ([string]::IsNullOrWhiteSpace($hostname)) { $hostname = [string]$Row.InstanceOCID }
    $safeHost = New-SafeFileName $hostname
    $hostFolder = Join-Path $ExecutionRoot $safeHost
    Ensure-Directory $hostFolder

    $region = [string]$Row.Region
    $instanceId = [string]$Row.InstanceOCID
    $compartmentId = [string]$Row.CompartmentOCID
    $compartmentName = [string]$Row.CompartmentName
    $state = [string]$Row.State
    $ad = [string]$Row.AD
    if ([string]::IsNullOrWhiteSpace($ad)) { $ad = [string]$Row.AvailabilityDomain }
    $bootVolumeCsv = [string]$Row.BootVolumeOCID

    $backupName = ""
    $backupOcid = ""
    $finalStatus = ""
    $resultToken = "FAIL"
    $errorMessage = ""
    $bootVolumeId = ""

    [void](Prepare-VisualEvidenceWindow)

    Clear-Host
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "Processo de Backup do host `"$hostname`"" -ForegroundColor Cyan
    Write-Host "OCI Backup Manager v$ToolVersion - $ExecutionStamp" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "Data/Hora local: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')" -ForegroundColor Gray
    Write-Host "Evidencia visual: PowerShell maximizado no monitor principal; print full screen deve registrar relogio/data do Windows." -ForegroundColor Gray
    Write-Host "Region: $region" -ForegroundColor Gray
    Write-Host "Instance: $instanceId" -ForegroundColor Gray
    Write-Host "Compartment: $compartmentName" -ForegroundColor Gray
    Write-Host "BackupType: $BackupType" -ForegroundColor Gray
    Write-Host "DryRun: $([bool]$DryRun)" -ForegroundColor Gray
    Write-Host ""

    $bootVolumeLookup = Get-BootVolumeId `
        -BootVolumeFromCsv $bootVolumeCsv `
        -Region $region `
        -CompartmentId $compartmentId `
        -AvailabilityDomain $ad `
        -InstanceId $instanceId

    if (-not $bootVolumeLookup.Success) {
        $finalStatus = "ERRO_BOOT_VOLUME"
        $resultToken = "FAIL"
        $errorMessage = $bootVolumeLookup.Error
        Write-Bad $errorMessage
    }
    else {
        $bootVolumeId = $bootVolumeLookup.BootVolumeOCID
        Write-Ok "Boot Volume identificado: $bootVolumeId"

        $backupName = New-BackupDisplayName -Hostname $hostname -BackupType $BackupType

        if ($DryRun) {
            $finalStatus = "DRYRUN_VALIDATED"
            $resultToken = "DRYRUN"
            $errorMessage = "DryRun habilitado. Nenhum backup foi criado."
            Write-Warn "DryRun: o backup NAO sera criado."
            Write-Host "Backup planejado: $backupName" -ForegroundColor Gray
        }
        else {
            Write-Warn "Criando backup ${BackupType}: $backupName"
            $createResult = New-BootVolumeBackup -BootVolumeOCID $bootVolumeId -Region $region -BackupName $backupName -BackupType $BackupType

            if (-not $createResult.Success) {
                $finalStatus = "ERRO_AO_CRIAR_BACKUP"
                $resultToken = "FAIL"
                $errorMessage = $createResult.Error + " | " + $createResult.Raw
                Write-Bad "Erro ao criar backup."
                Write-Plain $createResult.Raw
            }
            else {
                $backupOcid = [string]$createResult.Data.data.id
                if ([string]::IsNullOrWhiteSpace($backupOcid)) {
                    $finalStatus = "ERRO_OCID_BACKUP_AUSENTE"
                    $resultToken = "FAIL"
                    $errorMessage = "OCI CLI nao retornou OCID do backup criado."
                    Write-Bad $errorMessage
                }
                else {
                    Write-Ok "Backup criado: $backupOcid"
                    Write-Warn "Aguardando backup atingir estado final..."
                    $waitResult = Wait-BootVolumeBackupFinalState -BackupOCID $backupOcid -Region $region
                    $finalStatus = $waitResult.FinalStatus
                    $errorMessage = $waitResult.Error
                    if ($waitResult.Success) {
                        $resultToken = "SUCCESS"
                        Write-Ok "Backup concluido com sucesso."
                    }
                    else {
                        $resultToken = "FAIL"
                        Write-Bad "Backup finalizado sem sucesso: $finalStatus"
                    }
                }
            }
        }
    }

    $finalBaseName = "OCI_Backup_Manager_{0}_{1}_{2}" -f $safeHost, (Get-Date -Format "yyyyMMdd-HHmmss"), $resultToken
    $evidenceTxt = Join-Path $hostFolder ($finalBaseName + ".txt")
    $evidenceJson = Join-Path $hostFolder ($finalBaseName + ".json")
    $evidenceJpg = Join-Path $hostFolder ($finalBaseName + ".jpg")

    $evidence = [pscustomobject]@{
        ToolName            = $ToolName
        ToolVersion         = $ToolVersion
        ToolBuild           = $ToolBuild
        ExecutionDateTime   = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
        Hostname            = $hostname
        Region              = $region
        CompartmentName     = $compartmentName
        CompartmentOCID     = $compartmentId
        InstanceOCID        = $instanceId
        State               = $state
        AvailabilityDomain  = $ad
        BootVolumeOCID      = $bootVolumeId
        BackupName          = $backupName
        BackupType          = $BackupType
        BackupOCID          = $backupOcid
        Result              = $resultToken
        FinalStatus         = $finalStatus
        DryRun              = [bool]$DryRun
        HostEvidenceFolder  = $hostFolder
        EvidenceTxt         = $evidenceTxt
        EvidenceJson        = $evidenceJson
        EvidenceJpg         = $evidenceJpg
        ScreenshotStatus    = "PENDING"
        ErrorMessage        = $errorMessage
    }

    $screenshotStatus = Save-BackupVisualEvidence -OutputPath $evidenceJpg
    $evidence.ScreenshotStatus = $screenshotStatus
    if ($screenshotStatus -ne "OK") {
        if (Test-Path $evidenceJpg) { Remove-Item $evidenceJpg -Force -ErrorAction SilentlyContinue }
        $evidence.EvidenceJpg = ""
    }

    Save-TextEvidence -OutputTxt $evidenceTxt -Evidence $evidence
    $evidence | ConvertTo-Json -Depth 10 | Out-File -FilePath $evidenceJson -Encoding UTF8 -Force

    Write-ConsolidatedLogs -LogRow $evidence

    if ($resultToken -eq "FAIL") { $Script:RunHadFailure = $true }

    Write-Host ""
    if ($resultToken -eq "SUCCESS") {
        Write-Ok "Backup $BackupType do host $hostname criado com sucesso."
    }
    elseif ($resultToken -eq "DRYRUN") {
        Write-Warn "DryRun do host $hostname concluido. Nenhum backup foi criado."
    }
    else {
        Write-Bad "Backup $BackupType do host $hostname finalizado com falha."
    }
    Write-Host "Evidencias: $hostFolder" -ForegroundColor Gray

    return $evidence
}

