    )

    Write-Host ""
    Write-Bad "CONFIRMACAO FINAL DE EXCLUSAO DE BACKUP OCI"
    Write-Warn "Esta acao excluira $Count Boot Volume Backup(s) informado(s) por OCID/CSV."
