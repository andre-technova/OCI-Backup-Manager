DELETE_REQUESTED: $requestedCount
DELETE_ERROR: $failCount
INPUT_CSV: $BackupDeleteInputCsv
REPORT_CSV: $reportCsv
REPORT_JSON: $reportJson
REPORT_JPG: $reportJpg
DATE_TIME: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
OBSERVACAO: Exclusao de Boot Volume Backup OCI. Use DryRun para validacao previa.
"@
    $txt | Out-File -FilePath $reportTxt -Encoding UTF8 -Force

    [void](Prepare-VisualEvidenceWindow)
    Clear-Host
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "$ToolName v$ToolVersion - Exclusao de Backups OCI" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Cyan
