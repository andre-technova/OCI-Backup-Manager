function ConvertFrom-OciValidateDateText {
    param([string]$Text)

    if ([string]::IsNullOrWhiteSpace($Text)) { return $null }

    $patterns = @(
        "yyyy-MM-dd HH:mm:ss",
        "MM/dd/yyyy HH:mm:ss",
        "M/d/yyyy HH:mm:ss"
    )

    foreach ($pattern in $patterns) {
        $dt = [datetime]::MinValue
        if ([datetime]::TryParseExact($Text.Trim(), $pattern, [System.Globalization.CultureInfo]::InvariantCulture, [System.Globalization.DateTimeStyles]::AssumeLocal, [ref]$dt)) {
            return $dt
        }
    }

    $cultures = @(
        [System.Globalization.CultureInfo]::InvariantCulture,
        [System.Globalization.CultureInfo]::GetCultureInfo("en-US"),
        [System.Globalization.CultureInfo]::CurrentCulture
    )

    foreach ($culture in $cultures) {
        $dt = [datetime]::MinValue
        if ([datetime]::TryParse($Text.Trim(), $culture, [System.Globalization.DateTimeStyles]::AssumeLocal, [ref]$dt)) {
            return $dt
        }
    }

    return $null
}

function Get-OciSessionStatus {
    param([switch]$Quiet)

    if (-not $Quiet) {
        Write-Info "Validando sessao OCI..."
    }

    $validateArgs = @("session", "validate", "--local", "--profile", $OciProfileName, "--auth", "security_token")
    $validate = & oci @validateArgs 2>&1
    $exitCode = $LASTEXITCODE
    $text = ($validate | Out-String).Trim()

    $expiration = $null
    if ($text -match "Session is valid until\s+(.+)$") {
        $expiration = ConvertFrom-OciValidateDateText -Text $Matches[1]
    }

    $ok = ($exitCode -eq 0 -and $text -notmatch "Session has expired|NotAuthenticated|not authenticated|expired")

    if (-not $Quiet) {
        if ($ok) {
            Write-Ok "Sessao OCI valida."
            if (-not [string]::IsNullOrWhiteSpace($text)) { Write-Host $text -ForegroundColor DarkGray }
            if ($null -ne $expiration) {
                $minutesLeft = [math]::Round((New-TimeSpan -Start (Get-Date) -End $expiration).TotalMinutes, 1)
                Write-Host "Tempo restante estimado: $minutesLeft minuto(s)." -ForegroundColor DarkGray
            }
        }
        else {
            Write-Warn "Sessao OCI invalida ou expirada."
            if (-not [string]::IsNullOrWhiteSpace($text)) { Write-Host $text -ForegroundColor DarkYellow }
        }
    }

    return [pscustomobject]@{
        Ok         = $ok
        Text       = $text
        Expiration = $expiration
        ExitCode   = $exitCode
    }
}

function Invoke-OciSessionRefresh {
    param([switch]$Quiet)

    if (-not $Quiet) { Write-Warn "Tentando renovar sessao OCI via 'oci session refresh'..." }

    $refreshArgs = @("session", "refresh", "--profile", $OciProfileName)
    $refresh = & oci @refreshArgs 2>&1
    $refreshExitCode = $LASTEXITCODE
    $refreshText = ($refresh | Out-String).Trim()

    if ($refreshExitCode -ne 0) {
        if (-not $Quiet) {
            Write-Warn "Refresh da sessao falhou."
            if (-not [string]::IsNullOrWhiteSpace($refreshText)) { Write-Host $refreshText -ForegroundColor DarkYellow }
        }
        return $false
    }

    if (-not $Quiet) { Write-Ok "Refresh executado. Revalidando sessao..." }
    $status = Get-OciSessionStatus -Quiet
    if ($status.Ok) {
        $Script:CachedOciSessionStatus = $status
        $Script:LastOciSessionValidation = Get-Date
        if (-not $Quiet) {
            Write-Ok "Sessao OCI renovada com sucesso."
            if (-not [string]::IsNullOrWhiteSpace($status.Text)) { Write-Host $status.Text -ForegroundColor DarkGray }
        }
        return $true
    }

    if (-not $Quiet) { Write-Warn "Refresh executou, mas a sessao ainda nao ficou valida." }
    return $false
}

function Invoke-OciAuthenticationVisible {
    param([switch]$Quiet)

    if (-not $Quiet) {
        Write-Host ""
        Write-Warn "Abrindo autenticacao OCI em modo visivel..."
        Write-Warn "Use o navegador que sera aberto pela OCI. Quando concluir, volte aqui."
        Write-Host ""
    }

    $authArgs = @(
        "session", "authenticate",
        "--profile-name", $OciProfileName,
        "--region", $OciLoginRegion,
        "--tenancy-name", $OciTenancyName,
        "--identity-provider-name", $OciIdpName,
        "--session-expiration-in-minutes", ([string]$SessionExpirationMinutes)
    )

    & oci @authArgs
    $authExitCode = $LASTEXITCODE
    if ($authExitCode -ne 0) {
        if (-not $Quiet) { Write-Bad "Falha na autenticacao OCI. Codigo: $authExitCode" }
        return $false
    }

    $status = Get-OciSessionStatus -Quiet
    if ($status.Ok) {
        $Script:CachedOciSessionStatus = $status
        $Script:LastOciSessionValidation = Get-Date
        if (-not $Quiet) { Write-Ok "Autenticacao OCI OK apos login." }
        return $true
    }

    if (-not $Quiet) {
        Write-Bad "Autenticacao nao ficou valida apos login."
        if (-not [string]::IsNullOrWhiteSpace($status.Text)) { Write-Host $status.Text -ForegroundColor DarkYellow }
    }
    return $false
}

function Ensure-OciAuth {
    <#
        PT-BR: valida, renova e, se necessario, abre autenticacao OCI antes de chamadas sensiveis.
        EN-US: validates, refreshes, and when needed starts OCI authentication before sensitive calls.
        ES-ES: valida, renueva y, si es necesario, abre autenticacion OCI antes de llamadas sensibles.
    #>
    param([switch]$Quiet)

    # Evita validar a cada segundo em loops de polling, mas revalida com folga operacional.
    if ($Quiet -and $null -ne $Script:CachedOciSessionStatus -and $Script:CachedOciSessionStatus.Ok) {
        $ageSeconds = (New-TimeSpan -Start $Script:LastOciSessionValidation -End (Get-Date)).TotalSeconds
        if ($ageSeconds -lt 60) {
            return $true
        }
    }

    $status = Get-OciSessionStatus -Quiet:$Quiet
    $Script:CachedOciSessionStatus = $status
    $Script:LastOciSessionValidation = Get-Date

    if ($status.Ok) {
        if ($null -ne $status.Expiration) {
            $minutesLeft = (New-TimeSpan -Start (Get-Date) -End $status.Expiration).TotalMinutes
            if ($minutesLeft -le [double]$SessionRefreshThresholdMinutes) {
                if (-not $Quiet) {
                    Write-Warn "Sessao com $([math]::Round($minutesLeft,1)) minuto(s) restante(s). Renovando antes de continuar..."
                }
                if (Invoke-OciSessionRefresh -Quiet:$Quiet) { return $true }
                return (Invoke-OciAuthenticationVisible -Quiet:$Quiet)
            }
        }
        return $true
    }

    # Primeiro tenta refresh, porque em alguns cenarios ainda existe material local para renovar.
    if (Invoke-OciSessionRefresh -Quiet:$Quiet) { return $true }

    # Diferente da primeira versao, o comportamento agora acompanha o Inventory Manager:
    # sessao expirada abre login assistido em vez de encerrar seco.
    return (Invoke-OciAuthenticationVisible -Quiet:$Quiet)
}

function Invoke-OciCliJson {
    param(
        [string]$Context,
        [string[]]$Arguments,
        [string]$Region = ""
    )

    if (-not (Ensure-OciAuth -Quiet)) {
        return [pscustomobject]@{
            Success = $false
            Context = $Context
            Data    = $null
            Raw     = ""
            Error   = "Sessao OCI invalida antes de executar: $Context"
        }
    }

    $finalArgs = Add-OciCommonArgs -Arguments $Arguments -Region $Region
    $raw = & oci @finalArgs 2>&1
    $exit = $LASTEXITCODE
    $text = ($raw | Out-String).Trim()

    if ($exit -ne 0) {
        return [pscustomobject]@{
            Success = $false
            Context = $Context
            Data    = $null
            Raw     = $text
            Error   = "OCI CLI retornou codigo $exit em: $Context"
        }
    }

    try {
        $json = $text | ConvertFrom-Json
        return [pscustomobject]@{
            Success = $true
            Context = $Context
            Data    = $json
            Raw     = $text
            Error   = ""
        }
    }
    catch {
        return [pscustomobject]@{
            Success = $false
            Context = $Context
            Data    = $null
            Raw     = $text
            Error   = "Falha ao interpretar JSON em: $Context - $($_.Exception.Message)"
        }
    }
}

function Import-InventoryCsv {
    Write-Info "Validando inventario OCI: $InputCsv"

    if (-not (Test-Path $InputCsv)) {
