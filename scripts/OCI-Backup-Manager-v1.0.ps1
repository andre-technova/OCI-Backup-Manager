function Get-OciListDataItems {
    param([object]$OciResult)

    if ($null -eq $OciResult -or $null -eq $OciResult.Data) { return @() }

    try {
        $dataObject = $OciResult.Data
        $dataProperty = $dataObject.PSObject.Properties | Where-Object { $_.Name -eq "data" } | Select-Object -First 1
        if ($null -ne $dataProperty) {
            if ($null -eq $dataProperty.Value) { return @() }
            return @($dataProperty.Value)
        }

        if ($dataObject -is [System.Collections.IEnumerable] -and -not ($dataObject -is [string])) {
            return @($dataObject)
        }

        return @($dataObject)
    }
    catch {
        Write-Warn "Falha ao normalizar lista retornada pelo OCI CLI: $($_.Exception.Message)"
        return @()
    }
}

